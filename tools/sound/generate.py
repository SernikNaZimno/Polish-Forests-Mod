"""Generates the sounds of the mod with tools/sound (step FA4 of the vertical slice, decision G.62-d, rule KFA-7).

Usage (Git Bash, project directory; Python 3.10+ with NumPy):
    python tools/sound/generate.py --wav <dir>               writes the WAV files (16-bit mono, 44.1 kHz) under <dir>
                                                             and sounds.json and the license manifest into the project
    python tools/sound/generate.py --wav <dir> --out <root>  the JSON files under another root (for comparisons)
    ./gradlew generateSound                                  the same, then encodes the WAV files to OGG Vorbis (mono,
                                                             quality 0.4) with the pure-Java port of libvorbis
                                                             (com.github.axet:jvorbis, from Maven Central, only in the
                                                             task's own configuration) into the resources

Files (paths relative to the project or --out):
    src/main/resources/assets/polishforests/sounds.json               the sound events, files and subtitles
    src/main/resources/assets/polishforests/sounds/manifest.json      source and license of every sound file
    <wav dir>/<path>.wav  for every src/main/resources/assets/polishforests/sounds/<path>.ogg
checkSound (Gradle; tools/sound/check.py) decodes the committed OGG files with JOrbis (the decoder of the game) and
compares them with a fresh run of this generator with a tolerance (measure.py), and the JSON files parsed.
"""
import argparse
import json
import os
import sys
import wave

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import recipes  # noqa: E402
import synth  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
ASSETS = 'src/main/resources/assets/polishforests'
SOUNDS_JSON = f'{ASSETS}/sounds.json'
MANIFEST = f'{ASSETS}/sounds/manifest.json'
SOUNDS_DIR = f'{ASSETS}/sounds'
LICENSE = 'CC BY 4.0'
LICENSE_URL = 'https://creativecommons.org/licenses/by/4.0/'
AUTHOR = 'SernikNaZimno (Polish Forests)'
QUALITY = 0.4


def sounds_json():
    out = {}
    for voice in recipes.VOICES:
        out[voice.event] = {
            'sounds': [f'polishforests:{voice.path}_{n}' for n in range(1, voice.variants + 1)],
            'subtitle': f'subtitles.polishforests.{voice.event}',
        }
    return out


def manifest():
    entries = []
    for voice, n, rel, seed in recipes.files():
        entries.append({
            'file': f'{rel}.ogg',
            'event': f'polishforests:{voice.event}',
            'source': f'synthesized by tools/sound/recipes.py, recipe {voice.recipe.__name__}, variant {n}, seed {seed}',
            'description': voice.description,
            'author': AUTHOR,
            'license': LICENSE,
            'license_url': LICENSE_URL,
            'recordings': 'none',
        })
    return {
        'comment': 'Generated by tools/sound/generate.py; do not edit. Every sound of the mod with its source and license. '
                   f'Encoded as mono OGG Vorbis {synth.RATE} Hz, quality {QUALITY}, by the Gradle task generateSound.',
        'rate': synth.RATE,
        'channels': 1,
        'files': entries,
    }


def write_wav(path, samples):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with wave.open(path, 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(synth.RATE)
        w.writeframes(synth.to_pcm16(samples).tobytes())


def render_all():
    """Relative path (without extension) -> float samples, in the order of recipes.files()."""
    return {rel: recipes.render(voice, n, seed) for voice, n, rel, seed in recipes.files()}


def dumps(obj):
    return json.dumps(obj, indent=1, ensure_ascii=False) + '\n'


def write_json(root):
    for rel, obj in ((SOUNDS_JSON, sounds_json()), (MANIFEST, manifest())):
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(dumps(obj))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--wav', required=True, help='directory for the WAV files')
    ap.add_argument('--out', help='root directory for sounds.json and the manifest (default: the project)')
    a = ap.parse_args()
    rendered = render_all()
    for rel, x in rendered.items():
        write_wav(os.path.join(a.wav, rel + '.wav'), x)
    lines = ['# Written by tools/sound/generate.py for SoundCodec encode', f'quality={QUALITY}', f'rate={synth.RATE}', '']
    with open(os.path.join(a.wav, 'encode.properties'), 'w', encoding='utf-8', newline=chr(10)) as f:
        f.write(chr(10).join(lines))
    write_json(a.out or ROOT)
    total = sum(len(x) for x in rendered.values()) / synth.RATE
    print(f'sound: wrote {len(rendered)} WAV files ({total:.1f} s) under {a.wav} and the JSON files under {a.out or ROOT}')


if __name__ == '__main__':
    main()
