"""Generates CREDITS.md (repository root) from tools/art/palettes.json, the recipes and the sound recipes of tools/sound.

CREDITS.md lists the licenses of the code and the assets and every outside source the assets were made with: the CC0 and
public-domain photos the palettes were measured from (only colors are taken, decision D5) and the sounds (step FA4: all
synthesized by tools/sound, no recordings; a CC0 / CC BY recording, if one is ever added, is listed with its author). checkArt fails when the file is not up to date; regenerate it with tools/art/generate.py.

Usage: python tools/art/credits.py [--check]
"""
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import recipes  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
CREDITS = os.path.join(ROOT, 'CREDITS.md')
PALETTES = os.path.join(HERE, 'palettes.json')
SOUND_TOOLS = os.path.join(ROOT, 'tools', 'sound')


def sound_voices():
    """The voices of tools/sound/recipes.py (loaded under another module name: tools/art has its own recipes)."""
    if SOUND_TOOLS not in sys.path:
        sys.path.append(SOUND_TOOLS)
    spec = importlib.util.spec_from_file_location('sound_recipes', os.path.join(SOUND_TOOLS, 'recipes.py'))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.VOICES


def sounds_section():
    out = [
        '## Sounds',
        '',
        'Every sound of the mod is synthesized by `tools/sound` (Python and NumPy recipes written from field-guide'
        ' descriptions of the calls: note frequencies, lengths, rhythm) and encoded to OGG Vorbis by the Gradle task'
        ' `generateSound`. No recording was used, traced or resampled, and no Minecraft sound was copied: the other'
        ' sounds the mod plays are vanilla sounds referenced by their identifiers. License CC BY 4.0, author'
        ' SernikNaZimno; every file with its recipe and seed is listed in'
        ' `src/main/resources/assets/polishforests/sounds/manifest.json`.',
        '',
        '| Sound event | Files | Source |',
        '|---|---|---|',
    ]
    for v in sound_voices():
        out.append(f'| `polishforests:{v.event}` | {v.variants} | synthesized, recipe `{v.recipe.__name__}`'
                   f' ({v.description}) |')
    out.append('')
    return out


def render():
    with open(PALETTES, encoding='utf-8') as f:
        pal = json.load(f)
    used = {}
    for tex in recipes.TEXTURES:
        if tex.palette:
            how = tex.palette_use or ('reference for the tint' if tex.tint else None)
            used.setdefault(tex.palette, []).append(f'`{tex.name}`' + (f' ({how})' if how else ''))
        if tex.name.startswith('scots_pine_bark'):
            used.setdefault('scots_pine_upper_bark', []).append(f'`{tex.name}` (rust tone)')
        if tex.name.startswith('scots_pine_transition_'):
            used.setdefault('scots_pine_upper_bark', []).append(f'`{tex.name}` (orange bark tones)')
    out = [
        '# Credits',
        '',
        '<!-- Generated by tools/art/credits.py from tools/art/palettes.json and tools/art/recipes.py; do not edit. -->',
        '',
        '## Licenses',
        '',
        '- **Code** (Java sources, build scripts, tools): MIT, see `LICENSE`.',
        '- **Assets** (textures and other art in `src/main/resources/assets/polishforests/`, block and item models,'
        ' animations and sounds made for this mod): Creative Commons Attribution 4.0 International (CC BY 4.0),'
        ' see `LICENSE-assets`. Attribution: "Polish Forests by SernikNaZimno"'
        ' (https://github.com/SernikNaZimno/Polish-Forests-Mod).',
        '- Textures are generated procedurally by `tools/art` (recipes, palettes and style lint in the repository),'
        ' animal models, animations and their textures by `tools/fauna` (species measures, painter and validator in the'
        ' repository), sounds by `tools/sound` (synthesis recipes in the repository).'
        ' Minecraft textures, models and sounds are not included: vanilla assets are only referenced by their'
        ' identifiers, and no file of Mojang or of other mods was copied, traced or edited.',
        '- Textures computed in the client: the planks of several woods of the mod and the wooden items made from'
        ' them (doors, trapdoors, shelves, signs and hanging signs with their edit screens, boats and chest boats) are'
        ' not files of the mod. The game client computes them when it loads resources, by recoloring the vanilla'
        ' textures of the player\'s own game (atlas sources `polishforests:derived_planks` and'
        ' `polishforests:derived_wood`, and with them the sign screens and the boat entity textures), so no vanilla'
        ' pixel is in the repository or the mod jar; these images are'
        ' neither part of the mod nor covered by its license.',
        '',
        '## Palette reference photos',
        '',
        'The colors of some textures were measured (k-means clustering of a crop) from the photos below. Only the'
        ' resulting colors are used; the photos are not part of the mod or the repository, and nothing was traced'
        ' or scaled from them. All of them are CC0 or public domain; the authors are listed with thanks.',
        '',
        '| Palette | Used by | Photo | Author | License |',
        '|---|---|---|---|---|',
    ]
    for name, p in pal['palettes'].items():
        users = ', '.join(used.get(name, [])) or '(not used yet)'
        photos = list(dict.fromkeys(f['source'] for f in p['from']))     # one row per photo (a photo may give 2 crops)
        for i, sid in enumerate(photos):
            s = pal['sources'][sid]
            lic = f'[{s["license"]}]({s["license_url"]})' if s.get('license_url') else s['license']
            out.append(f'| {"`" + name + "`" if i == 0 else ""} | {users if i == 0 else ""} | [{s["title"]}]({s["url"]}) '
                       f'| {s["author"]} | {lic} |')
    out.append('')
    out += sounds_section()
    return '\n'.join(out)


def write():
    with open(CREDITS, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render())


def is_current():
    if not os.path.exists(CREDITS):
        return False
    with open(CREDITS, encoding='utf-8') as f:
        return f.read().replace('\r\n', '\n') == render()


if __name__ == '__main__':
    if '--check' in sys.argv:
        ok = is_current()
        print('credits: CREDITS.md is ' + ('up to date' if ok else 'OUT OF DATE (run python tools/art/generate.py)'))
        sys.exit(0 if ok else 1)
    write()
    print('credits: wrote', CREDITS)
