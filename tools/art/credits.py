"""Generates CREDITS.md (repository root) from tools/art/palettes.json and the recipes.

CREDITS.md lists the licenses of the code and the assets and every outside source the assets were made with: the CC0 and
public-domain photos the palettes were measured from (only colors are taken, decision D5) and, from step V16 on, the
CC0 / CC BY sounds. checkArt fails when the file is not up to date; regenerate it with tools/art/generate.py.

Usage: python tools/art/credits.py [--check]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import recipes  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
CREDITS = os.path.join(ROOT, 'CREDITS.md')
PALETTES = os.path.join(HERE, 'palettes.json')


def render():
    with open(PALETTES, encoding='utf-8') as f:
        pal = json.load(f)
    used = {}
    for tex in recipes.TEXTURES:
        if tex.palette:
            how = tex.palette_use or ('reference for the tint' if tex.tint else None)
            used.setdefault(tex.palette, []).append(f'`{tex.name}`' + (f' ({how})' if how else ''))
        if tex.name.startswith('scots_pine_bark'):
            used.setdefault('scots_pine_upper_bark', []).append(f'`{tex.name}` (fissure and rust tones)')
    out = [
        '# Credits',
        '',
        '<!-- Generated by tools/art/credits.py from tools/art/palettes.json and tools/art/recipes.py; do not edit. -->',
        '',
        '## Licenses',
        '',
        '- **Code** (Java sources, build scripts, tools): MIT, see `LICENSE`.',
        '- **Assets** (textures and other art in `src/main/resources/assets/polishforests/`, block and item models,'
        ' animations and sounds made for this mod): Creative Commons Attribution 4.0 International (CC BY 4.0),'
        ' see `LICENSE-assets`. Attribution: "Polish Forests by SernikNaZimno"'
        ' (https://github.com/SernikNaZimno/Polish-Forests-Mod).',
        '- Textures are generated procedurally by `tools/art` (recipes, palettes and style lint in the repository).'
        ' Minecraft textures, models and sounds are not included: vanilla assets are only referenced by their'
        ' identifiers, and no file of Mojang or of other mods was copied, traced or edited.',
        '',
        '## Palette reference photos',
        '',
        'The colors of some textures were measured (k-means clustering of a crop) from the photos below. Only the'
        ' resulting colors are used; the photos are not part of the mod or the repository, and nothing was traced'
        ' or scaled from them. All of them are CC0 or public domain; the authors are listed with thanks.',
        '',
        '| Palette | Used by | Photo | Author | License |',
        '|---|---|---|---|---|',
    ]
    for name, p in pal['palettes'].items():
        users = ', '.join(used.get(name, [])) or '(not used yet)'
        photos = list(dict.fromkeys(f['source'] for f in p['from']))     # one row per photo (a photo may give 2 crops)
        for i, sid in enumerate(photos):
            s = pal['sources'][sid]
            lic = f'[{s["license"]}]({s["license_url"]})' if s.get('license_url') else s['license']
            out.append(f'| {"`" + name + "`" if i == 0 else ""} | {users if i == 0 else ""} | [{s["title"]}]({s["url"]}) '
                       f'| {s["author"]} | {lic} |')
    out += [
        '',
        '## Sounds',
        '',
        'None yet (sounds will be CC0 or CC BY only, listed here with their authors).',
        '',
    ]
    return '\n'.join(out)


def write():
    with open(CREDITS, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render())


def is_current():
    if not os.path.exists(CREDITS):
        return False
    with open(CREDITS, encoding='utf-8') as f:
        return f.read().replace('\r\n', '\n') == render()


if __name__ == '__main__':
    if '--check' in sys.argv:
        ok = is_current()
        print('credits: CREDITS.md is ' + ('up to date' if ok else 'OUT OF DATE (run python tools/art/generate.py)'))
        sys.exit(0 if ok else 1)
    write()
    print('credits: wrote', CREDITS)
