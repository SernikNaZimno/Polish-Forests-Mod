"""Generates the animal assets of the mod from tools/fauna (step V8 of the vertical slice, rule ZW-9).

Usage (Git Bash, project directory; Python 3.10+ with Pillow and NumPy):
    python tools/fauna/generate.py            writes the files below
    python tools/fauna/generate.py --out <dir>   writes them under another root (for comparisons)
    ./gradlew generateArt                     the same, together with the block textures of tools/art

Files (paths relative to the project):
    src/main/resources/assets/polishforests/geckolib/models/entity/roe_deer.geo.json        model (format 1.12.0)
    src/main/resources/assets/polishforests/geckolib/animations/entity/roe_deer.animation.json
    src/main/resources/assets/polishforests/textures/entity/roe_deer/<doe|buck>_<summer|winter>.png
    src/main/resources/assets/polishforests/textures/item/roe_deer_spawn_egg.png
    src/gametest/resources/assets/polishforests_probe/...                                    the axis gauge (game test only)
    src/test/resources/fauna/fauna_expected.json   bone and locator positions, cameras of the 4-side views
    src/test/resources/fauna/<model>_<variant>_<view>.png   silhouettes of the 4-side views (preview from code)
The fauna game test (-Pgametest=fauna) compares the game with the last two; checkArt (tools/art/check.py) compares the
committed files with this generator (JSON parsed, PNG by decoded pixels) and runs the validator (validate.py).
"""
import argparse
import json
import os
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import animations  # noqa: E402
import paint  # noqa: E402
import render  # noqa: E402
import species  # noqa: E402
import uvpack  # noqa: E402
from model import geo_json, pivots_and_locators  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
ASSETS = 'src/main/resources/assets/polishforests'
PROBE_ASSETS = 'src/gametest/resources/assets/polishforests_probe'
EXPECTED = 'src/test/resources/fauna'

SEXES = ('doe', 'buck')
SEASONS = ('summer', 'winter')
ANTLERS = ('antler_left', 'antler_right')

# The 4-side views of the fauna game test: the camera stays, the animal turns (yaw in Minecraft degrees). The camera
# is given relative to the animal's feet; the game test builds a lime concrete backdrop and floor around them.
SCREEN = (854, 480)
FOV = 30
VIEW_CAMERA = dict(eye=(0.0, 0.62, -7.0), yaw=0.0, pitch=0.0)
VIEWS = (('front', 180.0), ('left', 270.0), ('back', 0.0), ('right', 90.0))


def packed(m):
    """Packs the UV of a model and sets the texture height to the smallest power of two (at least 16) that holds it."""
    rows = uvpack.pack(m)
    h = 16
    while h < rows:
        h *= 2
    m.texture_size = (m.texture_size[0], h)
    return m


def roe_deer():
    return packed(species.roe_deer())


def axis_gauge():
    return packed(species.axis_gauge())


def eat_pose_check(m, anims):
    """Height of the nose locator above the ground in the grazing pose (pixels)."""
    pose = animations.pose_at(anims['animations']['misc.eat'], 1.2)
    nose = pivots_and_locators(m, pose)['locator:nose']
    return float(nose[1])


def deer_animations(m):
    anims = animations.quadruped_animations(m)
    return anims


def view_camera():
    return render.Camera(VIEW_CAMERA['eye'], VIEW_CAMERA['yaw'], VIEW_CAMERA['pitch'], FOV, *SCREEN)


def build_all():
    """Relative path -> ('json', object) or ('png', RGBA array); plus the models for the validator and the sheets."""
    files = {}
    deer = roe_deer()
    deer_anims = deer_animations(deer)
    files[f'{ASSETS}/geckolib/models/entity/roe_deer.geo.json'] = ('json', geo_json(deer))
    files[f'{ASSETS}/geckolib/animations/entity/roe_deer.animation.json'] = ('json', deer_anims)
    textures, details = {}, {}
    for sex in SEXES:
        for season in SEASONS:
            img, det = paint.paint_model(deer, paint.roe_deer_shader(deer, sex, season), with_details=True)
            textures[(sex, season)] = img
            rel = f'{ASSETS}/textures/entity/roe_deer/{sex}_{season}.png'
            files[rel] = ('png', img)
            details[rel] = det
    files[f'{ASSETS}/textures/item/roe_deer_spawn_egg.png'] = ('png', paint.spawn_egg((186, 108, 60), (234, 220, 192)))

    gauge = axis_gauge()
    gauge_anims = animations.calibration_animations(species.AXIS_GAUGE_ANIM)
    files[f'{PROBE_ASSETS}/geckolib/models/entity/axis_gauge.geo.json'] = ('json', geo_json(gauge))
    files[f'{PROBE_ASSETS}/geckolib/animations/entity/axis_gauge.animation.json'] = ('json', gauge_anims)
    files[f'{PROBE_ASSETS}/textures/entity/axis_gauge.png'] = ('png', paint.paint_model(gauge, paint.gauge_shader))

    cam = view_camera()
    expected = {
        'comment': 'Generated by tools/fauna/generate.py; do not edit. Positions in model pixels (Bedrock axes: +X left, '
                   '+Y up, -Z front), cameras relative to the feet of the animal (blocks, Minecraft yaw and pitch).',
        'screen': list(SCREEN), 'fov': FOV,
        'camera': {'eye': list(VIEW_CAMERA['eye']), 'yaw': VIEW_CAMERA['yaw'], 'pitch': VIEW_CAMERA['pitch']},
        'views': [{'name': n, 'yaw': y} for n, y in VIEWS],
        'models': {},
    }
    expected['models']['roe_deer'] = {
        'rest': _round(pivots_and_locators(deer)),
        'hidden': {'doe': list(ANTLERS), 'buck': []},
        'masks': {},
    }
    for sex in SEXES:
        hidden = ANTLERS if sex == 'doe' else ()
        for name, yaw in VIEWS:
            mask = render.silhouette(deer, cam, None, (0, 0, 0), yaw, hidden)
            rel = f'{EXPECTED}/roe_deer_{sex}_{name}.png'
            files[rel] = ('mask', mask)
            expected['models']['roe_deer']['masks'][f'{sex}_{name}'] = os.path.basename(rel)
    expected['models']['axis_gauge'] = {
        'rest': _round(pivots_and_locators(gauge)),
        'posed': _round(pivots_and_locators(gauge, species.AXIS_GAUGE_ANIM)),
        'animation': 'calib.pose',
    }
    files[f'{EXPECTED}/fauna_expected.json'] = ('json', expected)
    return files, dict(deer=deer, deer_anims=deer_anims, deer_textures=textures, gauge=gauge, gauge_anims=gauge_anims,
                       details=details)


def _round(d):
    return {k: [round(float(x), 4) + 0.0 for x in v] for k, v in sorted(d.items())}


def to_png_array(kind, data):
    if kind == 'mask':
        a = np.zeros((*data.shape, 4), np.uint8)
        a[..., 3] = 255
        a[data, :3] = 255
        return a
    return data


def dumps(obj, indent=0):
    """JSON with one space of indentation per level and arrays of numbers on one line (short diffs)."""
    pad = ' ' * indent
    if isinstance(obj, dict):
        if not obj:
            return '{}'
        items = [f'{pad} {json.dumps(k)}: {dumps(v, indent + 1)}' for k, v in obj.items()]
        return '{\n' + ',\n'.join(items) + '\n' + pad + '}'
    if isinstance(obj, list):
        if all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in obj):
            return '[' + ', '.join(json.dumps(x) for x in obj) + ']'
        items = [f'{pad} {dumps(v, indent + 1)}' for v in obj]
        return '[\n' + ',\n'.join(items) + '\n' + pad + ']'
    return json.dumps(obj)


def save(kind, data, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if kind == 'json':
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(dumps(data))
            f.write('\n')
    elif kind == 'mask':
        Image.fromarray(data).convert('1').save(path, optimize=True)
    else:
        opaque = bool((data[..., 3] == 255).all())
        Image.fromarray(data[..., :3] if opaque else data, 'RGB' if opaque else 'RGBA').save(path, optimize=True)


def write_all(root=ROOT):
    files, models = build_all()
    for rel, (kind, data) in files.items():
        save(kind, data, os.path.join(root, rel))
    return files, models


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', help='root directory to write under (default: the project)')
    a = ap.parse_args()
    files, models = write_all(a.out or ROOT)
    print(f'fauna: wrote {len(files)} files under {a.out or ROOT}')
    print(f'fauna: roe deer eat pose: nose {eat_pose_check(models["deer"], models["deer_anims"]):.2f} px above the ground')


if __name__ == '__main__':
    main()
